// The webpackChunkName here will name this chunk (and thus the requested
// script) according to the file name. See https://webpack.js.org/api/module-methods/#magic-comments
// for details
const localesPromise = import(
  /* webpackChunkName: "[request]" */ `../../locales/${LANG}.json`
).then(lang => {
  // FIXED: 2026-11-10 新增 es / ja / pt 时，langHack 里没有这三门语言的块，
  // 而 formula_*、*_agent 这类动态 key 又不在 extracted-translations.json 白名单里
  // （不会进 bundle），只能靠生成文件补文案，否则界面直接显示原始 key。
  // 原有语言的覆盖顺序不变：locale < langHack < generatedLangHack。
  const newLang = {
    ...lang,
    ...langHack[LANG],
    ...((generatedLangHack && generatedLangHack[LANG]) || {}),
  }
  i18n.addResourceBundle(LANG, 'translation', newLang)
})

function getCookie(name) {
  const value = `; ${document.cookie}`
  const parts = value.split(`; ${name}=`)
  if (parts.length === 2) return parts.pop().split(';').shift()
  return null
}

export default localesPromise
